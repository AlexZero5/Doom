namespace Doom.Rendering;

/// <summary>
///     Детализация кадра. Узкое место игры — объём вывода в терминал, а он растёт с числом
///     ячеек разного цвета. Пока камера движется, глаз всё равно не успевает разглядеть детали,
///     поэтому трёхмерный вид рисуется в ещё меньшем разрешении и с огрублённым цветом
///     (динамическое разрешение, см. <see cref="SceneRenderer" />); стоит остановиться — следующий
///     кадр снова полный. Оружие, прицел и строка состояния всегда чёткие.
/// </summary>
internal enum MotionDetail
{
    /// <summary>Полное качество.</summary>
    Full,

    /// <summary>В движении: разрешение в 1.35 раза грубее, цвет 5 бит на канал.</summary>
    Soft,

    /// <summary>В движении, галка «Грубее»: разрешение вдвое грубее, цвет 4 бита на канал.</summary>
    Strong
}

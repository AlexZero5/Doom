namespace Doom.UI;

/// <summary>
///     Пиксельный шрифт 5×7 для меню: каждый глиф — сетка 5 на 7 «пикселей», которые
///     рисуются символами ▀ прямо в кадр. Меню рисуется одним шрифтом и потому
///     масштабируется вместе с экраном, как вся остальная псевдо-3D графика.
/// </summary>
internal static class PixelFont
{
    /// <summary>Ширина глифа в пикселях.</summary>
    public const int GlyphWidth = 5;

    /// <summary>Высота глифа в пикселях.</summary>
    public const int GlyphHeight = 7;

    /// <summary>Шаг между символами (глиф + 1 пиксельный зазор).</summary>
    public const int Advance = 6;

    /// <summary>Возвращает глиф или <c>null</c>, если символа нет в шрифте.</summary>
    public static string[]? Get(char value) =>
        Glyphs.TryGetValue(value, out string[]? rows) ? rows : null;

    /// <summary>Ширина строки в пикселях шрифта.</summary>
    public static int Measure(string text) =>
        text.Length == 0 ? 0 : text.Length * Advance - (Advance - GlyphWidth);

    /// <summary>Собирает словарь глифов из «сырых» многострочных строк.</summary>
    private static Dictionary<char, string[]> BuildGlyphs()
    {
        Dictionary<char, string[]> glyphs = new(GlyphData.Count);

        foreach ((char key, string raw) in GlyphData)
        {
            string[] rows = raw.Split('\n');
            glyphs[key] = rows;
        }

        return glyphs;
    }

